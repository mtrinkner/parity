/**
 * Runner — screens the active deal and writes the report (JSON + Markdown).
 * Usage: node run.js
 * Swap `deal` for any other multifamily deal object to reuse the engine.
 */
const fs = require("fs");
const path = require("path");
const { screen } = require("./ruleEngine");
const ruleset = require("./rules");
const deal = require("./exampleDeal");

const out = screen(deal, ruleset);
const dir = path.join(__dirname, "..");

// JSON (machine-readable — this is the shape the n8n workflow returns to Lovable)
fs.writeFileSync(path.join(dir, "example-risk-report.json"), JSON.stringify(out, null, 2));

// Markdown (human-readable IC-style report)
const money = s => s;
const L = [];
L.push(`# ${deal.meta.name} — Risk & Red-Flag Report`);
L.push(`*Generated by the Risk Engine (rule-set v${out.ruleSetVersion}) from ${out.generatedFrom}. Screening-level; not a substitute for full DD.*`);
L.push("");
L.push(`## Verdict`);
L.push(`**Composite risk score: ${out.score}/100 → ${out.verdict}**  ·  ${out.verdictNote}`);
L.push(`**Deal risk posture: ${out.dealRiskPosture}**${out.guardrailCapped ? "  ·  *verdict capped by guardrail flags*" : ""}`);
L.push(`Flags: ${out.counts.critical} critical · ${out.counts.high} high · ${out.counts.medium} medium · ${out.counts.low} low · ${out.counts.insufficientData} insufficient-data · ${out.counts.pass} pass`);
L.push("");
L.push(`### Top risks`);
out.topRisks.forEach(t => L.push(`- ${t}`));
L.push("");
const block = (title, arr) => {
  if (!arr.length) return;
  L.push(`## ${title}`);
  for (const f of arr) {
    L.push(`### ${f.ruleId} · ${f.rule}  —  **${f.severity}**${f.level?` (L${f.level})`:""}${f.guardrail?" · guardrail":""}`);
    L.push(`- **Category:** ${f.category}`);
    L.push(`- **Evidence:** ${f.evidence}`);
    L.push(`- **OM page:** ${f.omPage}`);
    L.push(`- **Why it matters:** ${f.whyItMatters}`);
    L.push(`- **Estimated financial impact:** ${f.financialImpact}`);
    L.push(`- **Recommended next action:** ${f.recommendedNextAction}`);
    L.push(`- **Additional DD required:** ${f.additionalDDRequired ? "Yes" : "No"}`);
    L.push("");
  }
};
block("Risk flags (triggered, most-severe first)", out.flags);
block("Insufficient data (must resolve before IC)", out.insufficientData);
block("Cleared / mitigants (rule set discriminates — these are strengths)", out.passes);
fs.writeFileSync(path.join(dir, "example-risk-report.md"), L.join("\n"));

// Console summary
console.log(`Score ${out.score}/100 → ${out.verdict} | posture ${out.dealRiskPosture}`);
console.log(`Flags: ${out.counts.critical}C ${out.counts.high}H ${out.counts.medium}M ${out.counts.low}L | insufficient ${out.counts.insufficientData} | pass ${out.counts.pass} | guardrailCapped=${out.guardrailCapped}`);
console.log("Top risks:"); out.topRisks.forEach(t => console.log("  - " + t));
console.log("Wrote example-risk-report.json and .md");
